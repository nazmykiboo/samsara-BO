SELECT i.id, l.id, 5000.000000, NULL
FROM inventory_items i, core_locations l
WHERE i.kode = 'BB-004' AND l.name = 'Samsara Central Kitchen'
  AND NOT EXISTS (
    SELECT 1 FROM inventory_min_stok_lokasi x WHERE x.item_id = i.id AND x.location_id = l.id
  );

